"""Optical amplifier (EDFA) model: gain, saturation, amplified spontaneous emission (ASE).

ASE convention: S_sp is the ASE power spectral density PER POLARISATION, in W/Hz,
    S_sp = n_sp (G - 1) h nu,       n_sp = (NF G - 1) / (2 (G - 1)),
so the total ASE power in optical bandwidth B_o (both polarisations) is 2 S_sp B_o.
"""
from __future__ import annotations

import math

import numpy as np

from config import H_PLANCK


def n_sp_from_nf(nf_db: float, gain_lin: float) -> float:
    """Spontaneous-emission factor from the noise figure (exact for G > 1; n_sp >= 1)."""
    nf = 10.0 ** (nf_db / 10.0)
    if gain_lin <= 1.0 + 1e-9:
        return 1.0
    return max((nf * gain_lin - 1.0) / (2.0 * (gain_lin - 1.0)), 1.0)


def quantum_limit_nf_db(gain_lin: float) -> float:
    """Minimum physically possible noise figure for gain G (n_sp = 1)."""
    return 10.0 * math.log10((2.0 * gain_lin - 1.0) / gain_lin) if gain_lin > 1 else 0.0


def ase_psd_per_pol(gain_lin: float, nf_db: float, freq_hz):
    """ASE PSD per polarisation (W/Hz) generated by ONE amplifier."""
    return n_sp_from_nf(nf_db, gain_lin) * max(gain_lin - 1.0, 0.0) * H_PLANCK * np.asarray(freq_hz, dtype=float)


def effective_gain_db(gain_db: float, p_in_total_w: float, psat_dbm: float, saturation: bool) -> float:
    """Gain after the optional output-power limit (total over all channels). Never below 0 dB."""
    if not saturation or p_in_total_w <= 0:
        return float(gain_db)
    p_in_dbm = 10.0 * math.log10(p_in_total_w / 1e-3)
    return float(max(min(gain_db, psat_dbm - p_in_dbm), 0.0))


def ase_power_w(psd_per_pol, bandwidth_hz):
    """Total ASE power (both polarisations) in an optical bandwidth."""
    return 2.0 * np.asarray(psd_per_pol) * bandwidth_hz
